#pragma once
#include <cereal/cereal.hpp>
// 名前空間 : PetaPetaPenguin::Data
namespace PetaPetaPenguin::Data {
    //-------------------------------------------------------------
    //! @struct ClickCounterSaveData
    //! @brief  クリック数をJSONへ保存/復元するためのデータ
    //-------------------------------------------------------------
    struct ClickCounterSaveData {
        int count = 0;

        //-------------------------------------------------------------
        //! @brief  cerealによるシリアライズ定義
        //-------------------------------------------------------------
        template <class Archive>
        void serialize(Archive& ar) {
            ar(CEREAL_NVP(count));
        }

        //-------------------------------------------------------------
        //! @brief  保存済みJSONを読み込む（存在しない場合はデフォルト値）
        //-------------------------------------------------------------
        static ClickCounterSaveData Load();

        //-------------------------------------------------------------
        //! @brief  現在の内容をJSONへ保存する
        //-------------------------------------------------------------
        void Save() const;
    };
}    // namespace PetaPetaPenguin::Data
